"""Ritualvision (edge-dash markers, ../Ritualvision).

Same camera.xml format and TUIO output as reacTIVision; runs in place (never copied) and
reads, from its own folder:
  camera.xml          shared format (tracker/engines/base.py)
  reacTIVision.xml    only <tuio port> and <image display equalize>
  ritualvision.xml    <recognizer block offset invert hold ids size_ref size_lo size_hi size_on>

Settings keys (`rv_*`):
  rv_block rv_offset rv_invert rv_hold rv_ids   line threshold and tracking
  rv_size_on rv_size_ref_px rv_size_lo_pct rv_size_hi_pct
      size range: a fold whose arm length rc is outside ref*(1-lo%) .. ref*(1+hi%) is
      dropped. ref comes from the contact measurement (two markers edge to edge).
"""

import math
import os

from tracker.engines.base import (
    COMMON_DEFAULTS, TrackerEngine, attr, bool_text, build_camera_xml, import_camera_xml,
    write_files, xbool, xml_root,
)
from tracker.engines.reactivision import import_reactivision_xml

RITUALVISION_EXE = os.path.join(os.path.expanduser("~"), "scramble_ritual", "Ritualvision",
                                "Ritualvision.exe")

RV_DEFAULTS = {
    "ritualvision_exe": "",      # "" = ~/scramble_ritual/Ritualvision/Ritualvision.exe
    "rv_block": 15,              # 선 판정 국소 임계값 창 (px, 홀수)
    "rv_offset": 12.0,           # 주변 평균보다 이만큼 어두우면 선
    "rv_invert": False,          # 선이 타일보다 밝을 때
    "rv_hold": 3,                # 놓친 마커를 유지할 프레임 수
    "rv_ids": "ids.json",        # ID 표 (Ritualvision 폴더 기준)
    # size range from the contact measurement (docs/tracker-switch-design.md 4장)
    "rv_size_on": True,          # 크기 필터 사용 (기준값이 있을 때만 동작)
    "rv_size_ref_px": 0.0,       # 기준 크기 rc (카메라 px), 0 = 미측정
    "rv_size_lo_pct": 10.0,      # 허용 하한 −%
    "rv_size_hi_pct": 10.0,      # 허용 상한 +%
    "rv_size_src": "",           # measured | "" (표시용)
    "rv_size_shape": 0.0,        # 마지막 측정의 중심거리 / rc (표시용)
    "rv_size_sigma_pct": 0.0,    # 마지막 측정의 흔들림 % (표시용)
}

# marker geometry (docs/markers/edge-v2): ID lines sit on an inset hexagon whose edges are
# 0.76 R from the centre (R = tile vertex radius). The fold arm rc spans one inset edge:
LINE_INSET_R = 0.76
RC_PER_R = LINE_INSET_R / math.cos(math.radians(30))          # 0.8776
#: two tiles edge to edge: centre distance = 2 x apothem = sqrt(3) R
CONTACT_RC_RATIO = math.sqrt(3.0) / RC_PER_R                   # 1.9737
SHAPE_TOL = 0.06             # measured d/rc within +-6% of CONTACT_RC_RATIO
#: the hi% above which a fold merged with the tile outline (+14%) is no longer caught
MERGE_GROWTH_PCT = 14.0


def find_ritualvision(override=""):
    """Ritualvision.exe: an explicit path if it exists, else the default install."""
    for c in (override, RITUALVISION_EXE):
        if c and os.path.isfile(c):
            return os.path.abspath(c)
    return None


def is_ritualvision(exe):
    return bool(exe) and os.path.basename(exe).lower().startswith("ritualvision")


def size_range(cfg):
    """(lo_px, hi_px) accepted by the size filter, or None when it is off / unmeasured."""
    c = {**RV_DEFAULTS, **cfg}
    ref = float(c.get("rv_size_ref_px") or 0.0)
    if not c.get("rv_size_on") or ref <= 0:
        return None
    lo = max(0.0, float(c.get("rv_size_lo_pct") or 0.0))
    hi = max(0.0, float(c.get("rv_size_hi_pct") or 0.0))
    return ref * (1.0 - lo / 100.0), ref * (1.0 + hi / 100.0)


def build_app_xml(cfg):
    """reacTIVision.xml as Ritualvision reads it: TUIO port and preview only."""
    c = {**COMMON_DEFAULTS, **cfg}
    return (
        '<?xml version="1.0" encoding="ISO-8859-1" ?>\n'
        '<reactivision>\n'
        '    <!-- generated by webui.exhibit_server for Ritualvision; edit via the web UI -->\n'
        f'    <tuio host="127.0.0.1" port="{int(c["rtv_tuio_port"])}" />\n'
        f'    <image display="{c["rtv_display"]}" equalize="{bool_text(c["rtv_equalize"])}" '
        'fullscreen="false" />\n'
        '</reactivision>\n'
    )


def build_ritualvision_xml(cfg):
    c = {**RV_DEFAULTS, **cfg}
    on = size_range(c) is not None
    return (
        '<?xml version="1.0" encoding="UTF-8" ?>\n'
        '<!-- generated by webui.exhibit_server; edit via the web UI.\n'
        '     block = threshold window px, offset = darkness margin, hold = frames a lost marker\n'
        '     stays alive, ids = id table. size_ref = fold arm length (px) from the contact\n'
        '     measurement; folds outside size_ref*(1-size_lo%)..size_ref*(1+size_hi%) are\n'
        '     dropped while size_on is true. -->\n'
        '<ritualvision>\n'
        f'    <recognizer block="{int(c["rv_block"])}" offset="{float(c["rv_offset"]):g}" '
        f'invert="{bool_text(c["rv_invert"])}" hold="{int(c["rv_hold"])}" ids="{c["rv_ids"]}"\n'
        f'                size_ref="{float(c["rv_size_ref_px"]):.2f}" '
        f'size_lo="{float(c["rv_size_lo_pct"]):g}" size_hi="{float(c["rv_size_hi_pct"]):g}" '
        f'size_on="{bool_text(on)}" />\n'
        '</ritualvision>\n'
    )


def import_ritualvision_xml(path):
    out = {}
    root = xml_root(path) if path else None
    rec = root.find("recognizer") if root is not None else None
    if rec is None:
        return out
    for key, a, conv in (("rv_block", "block", int), ("rv_offset", "offset", float),
                         ("rv_invert", "invert", xbool), ("rv_hold", "hold", int),
                         ("rv_ids", "ids", str), ("rv_size_ref_px", "size_ref", float),
                         ("rv_size_lo_pct", "size_lo", float), ("rv_size_hi_pct", "size_hi", float),
                         ("rv_size_on", "size_on", xbool)):
        v = attr(rec, a, conv)
        if v is not None:
            out[key] = v
    return out


def write_configs(cfg, work_dir):
    p = write_files(work_dir, {"camera.xml": build_camera_xml(cfg),
                               "reacTIVision.xml": build_app_xml(cfg)})
    p.update(write_files(work_dir, {"ritualvision.xml": build_ritualvision_xml(cfg)},
                         encoding="utf-8"))
    return p


class RitualvisionEngine(TrackerEngine):
    name = "ritualvision"
    label = "Ritualvision"
    fields = tuple(RV_DEFAULTS)
    kill_tree = True          # one-file exe: launcher + child holding the camera

    def find_exe(self, cfg, override=""):
        return find_ritualvision(cfg.get("ritualvision_exe", ""))

    def missing_exe_message(self):
        return (f"Ritualvision.exe 없음 - {RITUALVISION_EXE} 를 확인하거나 "
                "ritualvision_exe 경로를 지정하세요 (Ritualvision 폴더의 build.bat으로 빌드)")

    def write_configs(self, cfg, work_dir):
        p = write_configs(cfg, work_dir)
        return {"camera": p["camera.xml"], "rtv": p["reacTIVision.xml"],
                "ritualvision": p["ritualvision.xml"]}

    def import_configs(self, exe_dir):
        """The live files (not *.orig): they hold what this server last wrote."""
        d = exe_dir
        out = import_camera_xml(os.path.join(d, "camera.xml"))
        app = import_reactivision_xml(os.path.join(d, "reacTIVision.xml"))
        out.update({k: v for k, v in app.items()
                    if k in ("rtv_tuio_port", "rtv_display", "rtv_equalize")})
        out.update(import_ritualvision_xml(os.path.join(d, "ritualvision.xml")))
        return out
